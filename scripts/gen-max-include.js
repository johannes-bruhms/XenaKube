// scripts/gen-max-include.js
//
// Reads src/osc-schema.ts + src/swam-mapping.ts + src/face-gesture.ts via
// tsx and emits `max/gen_includes.js` — a pure data file that `xk_swam.js`
// pulls in via `include("gen_includes.js")`. One source of truth for OSC
// addresses, SWAM enums, CC-value maps, intensity/envelope/articulation/
// motion tables, and the 12 face signatures.
//
// Helper FUNCTIONS are NOT codegen'd — they live hand-written in
// xk_swam.js and hand-written in src/swam-mapping.ts, with vitest
// coverage over the TS copy. A drift in functions shows up as a broken
// sound (caught by listening), a drift in a table shows up as a silent
// numeric slip (caught by nothing) — so only the tables get codegen'd.
//
// Run: `node scripts/gen-max-include.js`   (npm: `npm run gen:max`)

require('tsx/cjs');

const fs   = require('fs');
const path = require('path');

const { OSC }          = require('../src/osc-schema.ts');
const {
  HARMONICS, TREMOLO, BOW_POLY,
  HARMONICS_CC_VAL, TREMOLO_CC_VAL, BOW_POLY_CC_VAL,
  INTENSITY_MAP, ENV_PROFILE, ART_OFF_VEL, MOTION_NUDGE,
  LEGATO_COMPLEX, REGIME_ATTACK_MULT, REGIME_EXPR_RAMP_MULT,
  buildFaceMap,
} = require('../src/swam-mapping.ts');

const OUT = path.resolve(__dirname, '..', 'max', 'gen_includes.js');

// Stable key ordering for deterministic output across runs.
function sortedJson(obj, indent) {
	if (Array.isArray(obj)) {
		return '[' + obj.map(v => sortedJson(v, indent)).join(', ') + ']';
	}
	if (obj !== null && typeof obj === 'object') {
		const keys = Object.keys(obj); // preserve TS declaration order
		const pad = ' '.repeat(indent);
		const inner = keys.map(k => `${pad}  ${quoteKey(k)}: ${sortedJson(obj[k], indent + 2)}`);
		return '{\n' + inner.join(',\n') + '\n' + pad + '}';
	}
	if (typeof obj === 'string') return JSON.stringify(obj);
	return String(obj);
}

function quoteKey(k) {
	// Bare word if it's a valid JS identifier, else quoted.
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
}

function block(name, value) {
	return `var ${name} = ${sortedJson(value, 0)};\n`;
}

const lines = [];
lines.push('// ================================================================');
lines.push('// max/gen_includes.js — GENERATED by scripts/gen-max-include.js');
lines.push('// DO NOT EDIT BY HAND. Source of truth: src/osc-schema.ts,');
lines.push('// src/swam-mapping.ts, src/face-gesture.ts. Regenerate via:');
lines.push('//     npm run gen:max');
lines.push('// ================================================================');
lines.push('');
lines.push('// ---------------- OSC addresses (/xk/* and /gan/*) ----------------');
lines.push(block('OSC', OSC));
lines.push('// ---------------- SWAM technique enums ---------------------------');
lines.push(block('HARMONICS', HARMONICS));
lines.push(block('TREMOLO',   TREMOLO));
lines.push(block('BOW_POLY',  BOW_POLY));
lines.push('// ---------------- Selector CC band centers (0..127) --------------');
lines.push(block('HARMONICS_CC_VAL', HARMONICS_CC_VAL));
lines.push(block('TREMOLO_CC_VAL',   TREMOLO_CC_VAL));
lines.push(block('BOW_POLY_CC_VAL',  BOW_POLY_CC_VAL));
lines.push('// ---------------- Intensity → Expr/Vel/Bow/Density/Trem ---------');
lines.push(block('INTENSITY_MAP', INTENSITY_MAP));
lines.push('// ---------------- Envelope profiles (per-note + per-phrase) ------');
lines.push(block('ENV_PROFILE', ENV_PROFILE));
lines.push('// ---------------- Articulation → note-off velocity ---------------');
lines.push(block('ART_OFF_VEL', ART_OFF_VEL));
lines.push('// ---------------- Motion → semitone nudge ------------------------');
lines.push(block('MOTION_NUDGE', MOTION_NUDGE));
lines.push('// ---------------- 12 face signatures (derived from TS source) ----');
lines.push(block('FACE_MAP', buildFaceMap()));
lines.push('// ---------------- Gliss (legato/portamento) complexes ------------');
lines.push(block('LEGATO_COMPLEX', LEGATO_COMPLEX));
lines.push('// ---------------- Regime → attack/expr ramp multipliers ----------');
lines.push(block('REGIME_ATTACK_MULT',    REGIME_ATTACK_MULT));
lines.push(block('REGIME_EXPR_RAMP_MULT', REGIME_EXPR_RAMP_MULT));

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`[gen:max] wrote ${OUT}`);
console.log(`[gen:max]   OSC addresses:  ${Object.keys(OSC).length}`);
console.log(`[gen:max]   face map rows:  ${Object.keys(buildFaceMap()).length}`);
console.log(`[gen:max]   env profiles:   ${Object.keys(ENV_PROFILE).length}`);
