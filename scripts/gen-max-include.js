// scripts/gen-max-include.js
//
// Reads src/osc-schema.ts + src/swam-mapping.ts + src/face-gesture.ts via
// tsx and emits `max/gen_includes.js` — a pure data file that `xk_swam.js`
// pulls in via `include("gen_includes.js")`. One source of truth for OSC
// addresses, SWAM enums, CC-value maps, intensity/envelope/articulation/
// motion tables, and the 12 face signatures.
//
// Helper FUNCTIONS are NOT codegen'd — they live hand-written in
// xk_swam.js and hand-written in src/swam-mapping.ts, with vitest
// coverage over the TS copy. A drift in functions shows up as a broken
// sound (caught by listening), a drift in a table shows up as a silent
// numeric slip (caught by nothing) — so only the tables get codegen'd.
//
// Run: `node scripts/gen-max-include.js`   (npm: `npm run gen:max`)

